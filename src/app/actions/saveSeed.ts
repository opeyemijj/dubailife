'use server'

import fs from 'fs';
import path from 'path';

export async function saveMapSeed(venues: any[], mapConfig: any) {
  try {
    const filePath = path.join(process.cwd(), 'src', 'data', 'mapSeed.ts');
    
    // Create the content
    const content = `// Auto-generated by Builder
export const mapConfig = ${JSON.stringify(mapConfig || {pitch: 45, yaw: 0, startX: -1000, startY: -500, startScale: 0.8}, null, 2)};

export const mapSeed = ${JSON.stringify(venues, null, 2)};
`;

    fs.writeFileSync(filePath, content, 'utf8');
    return { success: true };
  } catch (err: any) {
    console.error(err);
    return { success: false, error: err.message };
  }
}
